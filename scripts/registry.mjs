#!/usr/bin/env node
// Reads registry.json and writes the generated views into docs/. No dependencies.
//
//   node scripts/registry.mjs generate          write docs/*.md and the status block of each feature doc
//   node scripts/registry.mjs check             fail on an invalid registry, a doc out of step with its
//                                               stages, an unregistered component, or stale views
//   node scripts/registry.mjs snapshot v0.1     copy the views to docs/snapshots/v0.1/
//
// registry.json has three parts:
//   features   agensdet's own features; workflow state per stage (problem … release)
//   workflows  the plugin's main user journeys, step by step, each step pointing at a feature
//   existing   the audited existing work (VAS framework): components, workflows, task evidence

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = path.join(ROOT, 'registry.json');
const DOCS = path.join(ROOT, 'docs');
const PRODUCT_DOC = path.join(DOCS, 'README.md');

const TYPES = ['command', 'agent', 'skill', 'hook', 'mcp'];
const TYPE_LABEL = { command: 'Commands', agent: 'Agents', skill: 'Skills', hook: 'Hooks', mcp: 'MCP servers' };
const HEADER = '<!-- Generated by scripts/registry.mjs from registry.json. Do not edit by hand. -->\n\n';
const PLACEHOLDER = '_Not started._';

// ---------- feature workflow ----------

const STAGES = ['problem', 'workflow', 'design', 'spec', 'evals', 'build', 'release'];
const STAGE_LABEL = {
  problem: 'Problem', workflow: 'Workflow', design: 'Design', spec: 'Spec',
  evals: 'Evals', build: 'Build', release: 'Release',
};
// The doc sections each stage writes. Build writes code (checked through `path`), not doc text.
const STAGE_SECTIONS = {
  problem: ['### Users', '### Problems', '### What success looks like'],
  workflow: ['### Workflow today'],
  design: ['## Solution'],
  spec: ['## Behavior'],
  evals: ['## Quality'],
  build: [],
  release: ['## Changelog'],
};
const MARK = { 'not-started': '❌', draft: '🟡', approved: '✅' };

function stageState(value) {
  if (value === undefined || value === 'not-started') return 'not-started';
  if (value === 'draft') return 'draft';
  if (/^approved \d{4}-\d{2}-\d{2}$/.test(value)) return 'approved';
  return null;
}

const stateOf = (f, s) => stageState(f.stages?.[s]);
const isStarted = (f) => STAGES.some((s) => stateOf(f, s) !== 'not-started');

// The current stage is the first one not approved.
function featureStage(f) {
  if (f.released) return 'Released';
  const s = STAGES.find((x) => stateOf(f, x) !== 'approved');
  if (!s) return 'Ready';
  return `${STAGE_LABEL[s]}: ${stateOf(f, s)}`;
}
const featureColumn = (f) => featureStage(f).split(':')[0];

// ---------- existing-work evidence (audit) ----------

const STATES = ['idea', 'in-progress', 'works', 'deferred'];
const TASKS = ['spec', 'build', 'evals', 'real_use', 'docs'];
const TASK_VALUES = ['done', 'partial', 'missing'];
const TASK_MARK = { done: '✅', partial: '🟡', missing: '❌' };
const taskOf = (c, t) => c.tasks?.[t] ?? 'missing';

function evidenceStage(c) {
  if (c.state === 'idea') return 'Idea';
  if (taskOf(c, 'spec') !== 'done') return 'Spec';
  if (taskOf(c, 'build') !== 'done') return 'Build';
  if (taskOf(c, 'evals') !== 'done') return 'Eval';
  if (taskOf(c, 'docs') !== 'done' || taskOf(c, 'real_use') !== 'done') return 'Docs';
  return 'Ready';
}

// ---------- helpers ----------

function loadRegistry() {
  const reg = JSON.parse(fs.readFileSync(REGISTRY, 'utf8'));
  reg.features ??= [];
  reg.workflows ??= [];
  reg.existing ??= {};
  reg.existing.components ??= [];
  reg.existing.workflows ??= [];
  return reg;
}

const read = (p) => (fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null);

// Text under a heading, up to the next heading of the same or a higher level.
function sectionBody(md, heading) {
  const lines = md.split('\n');
  const start = lines.findIndex((l) => l.trim() === heading);
  if (start < 0) return null;
  const level = heading.match(/^#+/)[0].length;
  const stop = new RegExp(`^#{1,${level}} `);
  const out = [];
  for (const l of lines.slice(start + 1)) {
    if (stop.test(l)) break;
    out.push(l);
  }
  return out.join('\n').trim();
}

function problemIds() {
  const md = read(PRODUCT_DOC);
  if (!md) return null;
  const body = sectionBody(md, '## Problems') ?? '';
  return new Set(body.match(/\bP-\d+\b/g) ?? []);
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

// Components the plugin ships, found on disk.
function discover() {
  const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');
  const found = [];
  for (const f of walk(path.join(ROOT, 'skills'))) {
    if (path.basename(f) === 'SKILL.md') found.push({ type: 'skill', path: rel(path.dirname(f)) });
  }
  for (const type of ['command', 'agent']) {
    for (const f of walk(path.join(ROOT, `${type}s`))) if (f.endsWith('.md')) found.push({ type, path: rel(f) });
  }
  for (const [type, file] of [['hook', 'hooks/hooks.json'], ['mcp', '.mcp.json']]) {
    if (fs.existsSync(path.join(ROOT, file))) found.push({ type, path: file });
  }
  return found;
}

// ---------- status block inside each feature doc ----------

const BLOCK_START = '<!-- registry:start (generated from registry.json; do not edit) -->';
const BLOCK_END = '<!-- registry:end -->';

function statusBlock(f) {
  const board = path.relative(path.dirname(path.join(ROOT, f.doc)), path.join(DOCS, 'status-matrix.md')).split(path.sep).join('/');
  return [
    BLOCK_START,
    '| Type | Release | Solves | Stage |',
    '|------|---------|--------|-------|',
    `| ${f.type} | ${f.release} | ${(f.problems ?? []).join(', ') || '—'} | ${featureStage(f)} ([board](${board})) |`,
    BLOCK_END,
  ].join('\n');
}

function withStatusBlock(md, f) {
  const re = new RegExp(`${BLOCK_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${BLOCK_END}`);
  return re.test(md) ? md.replace(re, statusBlock(f)) : null;
}

// ---------- validation ----------

function validate(reg) {
  const errors = [];
  const pids = problemIds();
  if (!pids) errors.push('docs/README.md is missing (it holds the problem index).');

  const ids = new Set();
  for (const f of reg.features) {
    const who = f.id ?? '(no id)';
    if (!/^F-\d{3}$/.test(f.id ?? '')) errors.push(`${who}: feature ids look like F-001.`);
    if (ids.has(f.id)) errors.push(`${who}: duplicate id.`);
    ids.add(f.id);
    if (!f.name) errors.push(`${who}: name is missing.`);
    if (!TYPES.includes(f.type)) errors.push(`${who}: type must be one of ${TYPES.join(', ')}.`);
    if (!f.release) errors.push(`${who}: release is missing.`);
    for (const [s, v] of Object.entries(f.stages ?? {})) {
      if (!STAGES.includes(s)) errors.push(`${who}: unknown stage "${s}".`);
      else if (!stageState(v)) errors.push(`${who}: stage ${s} must be not-started, draft, or "approved YYYY-MM-DD".`);
    }
    // A stage starts only after the previous one is approved.
    STAGES.forEach((s, i) => {
      if (i && stateOf(f, s) !== 'not-started' && stateOf(f, STAGES[i - 1]) !== 'approved') {
        errors.push(`${who}: stage ${s} started before ${STAGES[i - 1]} was approved.`);
      }
    });
    for (const p of f.problems ?? []) {
      if (pids && !pids.has(p)) errors.push(`${who}: problem ${p} is not in the Problems section of docs/README.md.`);
    }
    if (f.path && !fs.existsSync(path.join(ROOT, f.path))) errors.push(`${who}: path "${f.path}" does not exist.`);
    if (stateOf(f, 'build') !== 'not-started' && !f.path) errors.push(`${who}: build has started, so path is required.`);
    for (const b of f.built_from ?? []) {
      if (!reg.existing.components.some((c) => c.id === b)) errors.push(`${who}: built_from "${b}" is not an existing component.`);
    }

    if (!isStarted(f) && !f.doc) continue;
    if (!f.doc) { errors.push(`${who}: a started feature needs a doc.`); continue; }
    const md = read(path.join(ROOT, f.doc));
    if (md === null) { errors.push(`${who}: doc "${f.doc}" does not exist.`); continue; }
    if (!md.includes(BLOCK_START) || !md.includes(BLOCK_END)) errors.push(`${who}: doc has no registry status block.`);
    for (const s of STAGES) {
      for (const h of STAGE_SECTIONS[s]) {
        const body = sectionBody(md, h);
        if (body === null) { errors.push(`${who}: doc is missing the "${h}" section.`); continue; }
        const empty = body === '' || body === PLACEHOLDER;
        if (stateOf(f, s) === 'not-started' && !empty) errors.push(`${who}: "${h}" has content but stage ${s} is not-started.`);
        if (stateOf(f, s) !== 'not-started' && empty) errors.push(`${who}: stage ${s} is ${stateOf(f, s)} but "${h}" is empty.`);
      }
    }
  }
  for (const f of reg.features) {
    for (const d of f.depends_on ?? []) if (!ids.has(d)) errors.push(`${f.id}: depends_on "${d}" is not a feature id.`);
  }
  for (const w of reg.workflows) {
    for (const s of w.steps ?? []) {
      if (s.feature && !ids.has(s.feature)) errors.push(`Workflow "${w.name}": step "${s.step}" uses unknown feature "${s.feature}".`);
    }
  }

  const ex = reg.existing;
  const exIds = new Set();
  for (const c of ex.components) {
    const who = c.id ?? '(no id)';
    if (!/^V-\d{2}$/.test(c.id ?? '')) errors.push(`existing ${who}: ids look like V-01.`);
    if (exIds.has(c.id)) errors.push(`existing ${who}: duplicate id.`);
    exIds.add(c.id);
    if (!TYPES.includes(c.type)) errors.push(`existing ${who}: type must be one of ${TYPES.join(', ')}.`);
    if (!STATES.includes(c.state)) errors.push(`existing ${who}: state must be one of ${STATES.join(', ')}.`);
    for (const [t, v] of Object.entries(c.tasks ?? {})) {
      if (!TASKS.includes(t)) errors.push(`existing ${who}: unknown task "${t}".`);
      if (!TASK_VALUES.includes(v)) errors.push(`existing ${who}: task ${t} must be one of ${TASK_VALUES.join(', ')}.`);
    }
    // existing/ is local reference material and is not committed; check paths only where it is present.
    if (c.path && fs.existsSync(path.join(ROOT, 'existing')) && !fs.existsSync(path.join(ROOT, c.path))) {
      errors.push(`existing ${who}: path "${c.path}" does not exist.`);
    }
  }
  for (const c of ex.components) {
    for (const d of c.depends_on ?? []) if (!exIds.has(d)) errors.push(`existing ${c.id}: depends_on "${d}" is not registered.`);
  }
  for (const w of ex.workflows) {
    for (const s of w.steps ?? []) {
      if (s.component && !exIds.has(s.component)) errors.push(`existing workflow "${w.name}": unknown component "${s.component}".`);
    }
  }

  const registered = new Set(reg.features.map((f) => f.path).filter(Boolean));
  for (const f of discover()) {
    if (!registered.has(f.path)) errors.push(`Unregistered ${f.type}: ${f.path} is on disk but no feature in registry.json has this path.`);
  }
  return errors;
}

// ---------- rendering ----------

const nodeId = (id) => 'n_' + String(id).replace(/[^A-Za-z0-9]/g, '_');
const label = (s) => String(s).replace(/"/g, "'");

function mermaidMap(items, stageText, cls) {
  let out = '```mermaid\nflowchart LR\n';
  for (const type of TYPES) {
    const group = items.filter((c) => c.type === type);
    if (!group.length) continue;
    out += `  subgraph ${type}s["${TYPE_LABEL[type]}"]\n`;
    for (const c of group) out += `    ${nodeId(c.id)}["${label(c.id)} ${label(c.name)}<br/>${label(stageText(c))}"]:::${cls(c)}\n`;
    out += '  end\n';
  }
  for (const c of items) for (const d of c.depends_on ?? []) out += `  ${nodeId(c.id)} --> ${nodeId(d)}\n`;
  out += '  classDef done stroke:#2e7d32,stroke-width:2px\n';
  out += '  classDef active stroke:#f9a825,stroke-width:2px\n';
  out += '  classDef todo stroke-dasharray:4 4\n';
  out += '  classDef parked stroke:#9e9e9e,stroke-dasharray:2 6\n';
  return out + '```\n';
}

function orphanList(items, workflows, key) {
  const used = new Set();
  for (const c of items) for (const d of c.depends_on ?? []) used.add(d);
  for (const w of workflows) for (const s of w.steps ?? []) if (s[key]) used.add(s[key]);
  const o = items.filter((c) => !['command', 'hook'].includes(c.type) && !used.has(c.id));
  return o.length ? o.map((c) => `- ${c.id} ${c.name} (${c.type})`).join('\n') + '\n' : 'None.\n';
}

function mermaidWorkflows(workflows, byId, key, prefix) {
  let out = '';
  workflows.forEach((w, wi) => {
    out += `## ${w.name}\n\n`;
    const steps = w.steps ?? [];
    if (!steps.length) { out += 'No steps yet.\n\n'; return; }
    out += '```mermaid\nflowchart LR\n';
    steps.forEach((s, i) => {
      const c = byId.get(s[key]);
      const who = c ? `${label(c.id)} ${label(c.name)}` : 'GAP: nothing covers this step';
      out += `  ${prefix}${wi}s${i}["${label(s.step)}<br/>${who}"]${c ? '' : ':::gap'}\n`;
      if (i) out += `  ${prefix}${wi}s${i - 1} --> ${prefix}${wi}s${i}\n`;
    });
    out += '  classDef gap stroke:#c62828,stroke-width:2px,stroke-dasharray:4 4\n```\n\n';
    const gaps = steps.filter((s) => !byId.get(s[key]));
    if (gaps.length) out += 'Gaps: ' + gaps.map((s) => s.step).join('; ') + '\n\n';
  });
  return out;
}

const featureClass = (f) => {
  const st = featureStage(f);
  if (st === 'Ready' || st === 'Released') return 'done';
  return isStarted(f) ? 'active' : 'todo';
};

function componentMap(reg) {
  let out = HEADER + '# Component map\n\nagensdet\'s features and who uses whom. An arrow from A to B means A uses B.\n\n';
  if (!reg.features.length) return out + 'No features registered yet.\n';
  out += mermaidMap(reg.features, featureStage, featureClass);
  out += '\nBorder: green = ready or released, yellow = in progress, dashed = not started.\n\n';
  out += '## Orphans\n\nFeatures nothing uses and no workflow includes.\n\n' + orphanList(reg.features, reg.workflows, 'feature');
  return out;
}

function workflowView(reg) {
  const out = HEADER + '# Workflow view\n\nThe plugin\'s main user journeys. A step no feature covers is a gap.\n\n';
  if (!reg.workflows.length) return out + 'No workflows registered yet.\n';
  return out + mermaidWorkflows(reg.workflows, new Map(reg.features.map((f) => [f.id, f])), 'feature', 'w');
}

function statusMatrix(reg) {
  let out = HEADER + '# Status matrix\n\nThe feature board. ✅ approved, 🟡 draft, ❌ not started. A feature\'s stage is the first stage not yet approved.\n\n';
  if (!reg.features.length) return out + 'No features registered yet.\n';
  out += `| ID | Feature | Type | Release | ${STAGES.map((s) => STAGE_LABEL[s]).join(' | ')} | Stage |\n`;
  out += `|----|---------|------|---------|${STAGES.map(() => '---').join('|')}|-------|\n`;
  const sorted = [...reg.features].sort((a, b) => String(a.release).localeCompare(String(b.release)) || a.id.localeCompare(b.id));
  for (const f of sorted) {
    const name = f.doc ? `[${f.name}](${path.relative(DOCS, path.join(ROOT, f.doc)).split(path.sep).join('/')})` : f.name;
    out += `| ${f.id} | ${name} | ${f.type} | ${f.release} | ${STAGES.map((s) => MARK[stateOf(f, s)]).join(' | ')} | ${featureStage(f)} |\n`;
  }
  out += '\n## By stage\n\n';
  for (const col of ['Problem', 'Workflow', 'Design', 'Spec', 'Evals', 'Build', 'Release', 'Ready', 'Released']) {
    const n = reg.features.filter((f) => featureColumn(f) === col).length;
    if (n) out += `- ${col}: ${n}\n`;
  }
  const wip = reg.features.filter((f) => isStarted(f) && !['Ready', 'Released'].includes(featureStage(f)));
  out += `\nIn progress now: ${wip.length}${wip.length ? ' (' + wip.map((f) => f.id).join(', ') + ')' : ''}\n`;
  const byProblem = new Map();
  for (const f of reg.features) for (const p of f.problems ?? []) byProblem.set(p, [...(byProblem.get(p) ?? []), f.id]);
  const pids = [...(problemIds() ?? [])].sort((a, b) => Number(a.slice(2)) - Number(b.slice(2)));
  if (pids.length) {
    out += '\n## Problems and the features that solve them\n\nProblems are described in [docs/README.md](README.md).\n\n| Problem | Features |\n|---------|----------|\n';
    for (const p of pids) out += `| ${p} | ${(byProblem.get(p) ?? []).join(', ') || 'none yet'} |\n`;
  }
  return out;
}

function existingWork(reg) {
  const ex = reg.existing;
  let out = HEADER + '# Existing work (audit)\n\n';
  out += `Source: ${ex.source ?? 'TBD'}. The audit notes are kept locally in \`planning/00-existing-work.md\`. These components are reference material for agensdet's features, not agensdet features.\n\n`;
  if (!ex.components.length) return out + 'Nothing audited yet.\n';
  const evClass = (c) => ({ works: 'done', 'in-progress': 'active', idea: 'todo', deferred: 'parked' })[c.state];
  out += '## Component map\n\n' + mermaidMap(ex.components, evidenceStage, evClass);
  out += '\nBorder: green = works, yellow = in progress, dashed = idea, grey dashed = deferred.\n\n';
  out += '### Orphans\n\n' + orphanList(ex.components, ex.workflows, 'component') + '\n';
  out += '## Workflows\n\n' + mermaidWorkflows(ex.workflows, new Map(ex.components.map((c) => [c.id, c])), 'component', 'x').replace(/^## /gm, '### ');
  out += '## Evidence matrix\n\n✅ done, 🟡 partial, ❌ missing. The stage is the first column that is not ✅.\n\n';
  out += '| ID | Component | Type | State | Spec | Build | Evals | Real use | Docs | Stage |\n';
  out += '|----|-----------|------|-------|------|-------|-------|----------|------|-------|\n';
  for (const c of ex.components) {
    out += `| ${c.id} | ${c.name} | ${c.type} | ${c.state} | ${TASKS.map((t) => TASK_MARK[taskOf(c, t)]).join(' | ')} | ${evidenceStage(c)} |\n`;
  }
  return out;
}

function render(reg) {
  return {
    'component-map.md': componentMap(reg),
    'workflows.md': workflowView(reg),
    'status-matrix.md': statusMatrix(reg),
    'existing-work.md': existingWork(reg),
  };
}

// ---------- commands ----------

function fail(errors) {
  for (const e of errors) console.error('✗ ' + e);
  process.exit(1);
}

const [cmd = 'generate', arg] = process.argv.slice(2);
const reg = loadRegistry();
const errors = validate(reg);
const docsWithBlock = reg.features.filter((f) => f.doc && read(path.join(ROOT, f.doc)) !== null);

if (cmd === 'generate') {
  if (errors.length) fail(errors);
  fs.mkdirSync(DOCS, { recursive: true });
  const views = render(reg);
  for (const [name, text] of Object.entries(views)) fs.writeFileSync(path.join(DOCS, name), text);
  for (const f of docsWithBlock) {
    const file = path.join(ROOT, f.doc);
    fs.writeFileSync(file, withStatusBlock(read(file), f));
  }
  console.log(`Wrote ${Object.keys(views).map((n) => 'docs/' + n).join(', ')}` + (docsWithBlock.length ? ` and the status block in ${docsWithBlock.length} feature doc(s)` : ''));
} else if (cmd === 'check') {
  for (const [name, text] of Object.entries(render(reg))) {
    if (read(path.join(DOCS, name)) !== text) errors.push(`docs/${name} is out of date. Run: node scripts/registry.mjs generate`);
  }
  for (const f of docsWithBlock) {
    const md = read(path.join(ROOT, f.doc));
    const updated = withStatusBlock(md, f);
    if (updated !== null && updated !== md) errors.push(`${f.doc}: status block is out of date. Run: node scripts/registry.mjs generate`);
  }
  if (errors.length) fail(errors);
  console.log(`OK: ${reg.features.length} features, ${reg.workflows.length} workflows, ${reg.existing.components.length} existing components; docs up to date.`);
} else if (cmd === 'snapshot') {
  if (!arg) fail(['Usage: node scripts/registry.mjs snapshot <version>']);
  if (errors.length) fail(errors);
  const dir = path.join(DOCS, 'snapshots', arg);
  if (fs.existsSync(dir)) fail([`docs/snapshots/${arg} already exists. Snapshots are not overwritten.`]);
  fs.mkdirSync(dir, { recursive: true });
  for (const [name, text] of Object.entries(render(reg))) fs.writeFileSync(path.join(dir, name), text);
  fs.copyFileSync(REGISTRY, path.join(dir, 'registry.json'));
  console.log(`Snapshot written to docs/snapshots/${arg}/`);
} else {
  fail([`Unknown command "${cmd}". Use generate, check or snapshot <version>.`]);
}
